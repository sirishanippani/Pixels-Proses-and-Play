-- V1__init.sql (PostgreSQL)
-- Baseline schema. Mirrors the entity model as of Phase 5 completion.
-- Role is VARCHAR + CHECK (Postgres ENUM types are not portable with Hibernate's
-- EnumType.STRING without extra plumbing). Content fields are TEXT (Postgres
-- treats CLOB as TEXT; TEXT is unbounded).

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(255),
    email          VARCHAR(255),
    password       VARCHAR(255),
    bio            VARCHAR(255),
    profile_image  VARCHAR(255),
    role           VARCHAR(32) NOT NULL CHECK (role IN ('ROLE_ADMIN', 'ROLE_USER'))
);

CREATE TABLE posts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255),
    content     TEXT,
    created_at  TIMESTAMP(6),
    user_id     BIGINT,
    CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE tag (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE post_tags (
    post_id  BIGINT NOT NULL,
    tag_id   BIGINT NOT NULL,
    PRIMARY KEY (post_id, tag_id),
    CONSTRAINT fk_post_tags_post FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT fk_post_tags_tag  FOREIGN KEY (tag_id)  REFERENCES tag   (id)
);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     TEXT,
    created_at  TIMESTAMP(6),
    post_id     BIGINT,
    user_id     BIGINT,
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES users (id)
);
